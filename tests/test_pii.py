MUST_KEEP = [
    ("номер_ФЗ", "в соответствии со статьёй 22 Федерального закона от 05.04.2013 № 44-ФЗ",
     "05.04.2013"),
    ("номер_приложения", "Приложение № 2 к извещению о проведении запроса котировок",
     "Приложение № 2"),
    ("ИКЗ", "Идентификационный код закупки № 262712345678130100100500030000244.",
     "262712345678130100100500030000244"),
    ("срок_оплаты", "Оплата 250 000 руб. не позднее 15.09.2026 согласно контракту.",
     "15.09.2026"),
    ("код_ОКПД2", "Код ОКПД2 17.23.11 на поставку канцелярских товаров.", "17.23.11"),
    ("дата_выдачи", "Паспорт выдан 17.08.2019 отделом внутренних дел.", "17.08.2019"),
    ("страна", "Товар произведён в Российской Федерации.", "Российской Федерации"),
]


@pytest.mark.parametrize("label,text,keeper", MUST_KEEP, ids=[c[0] for c in MUST_KEEP])
def test_no_false_positive(label, text, keeper):
    out = clean(text)["cleaned_text"]
    assert keeper in out, f"{label}: не-PII было ошибочно вычищено"


def test_contract_terms_are_not_treated_as_names():
    """NER в казённых текстах любит помечать «Заказчик»/«Поставщик» как организации."""
    text = "«Заказчик» и «Поставщик» подписали настоящий Контракт в двух экземплярах."
    out = clean(text)["cleaned_text"]
    for term in ("Заказчик", "Поставщик", "Контракт"):
        assert term in out, f"договорный термин «{term}» не должен вычищаться"


def test_clean_text_is_idempotent():
    """Повторная очистка уже очищенного текста ничего не находит —
    значит плейсхолдеры не принимаются за новые сущности."""
    once = clean("Тел. 89261234567, ИНН 7712345678, ООО «Ромашка».")["cleaned_text"]
    twice = clean(once)
    assert twice["entities_found"] == 0
    assert twice["cleaned_text"] == once


def test_empty_text_does_not_crash():
    result = clean("")
    assert result["cleaned_text"] == ""
    assert result["entities_found"] == 0


