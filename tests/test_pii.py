"""Регрессионные тесты пайплайна очистки.

Две группы:
  * must_remove  — PII, которое обязано исчезнуть (утечка = провал);
  * must_keep    — «ловушки» из документов госзакупок, которые НЕ являются PII
                   и должны остаться нетронутыми (ложное срабатывание = провал).

Вторая группа фиксирует классы ложняков, найденные при прогоне реальных
документов с zakupki.gov.ru: номера ФЗ, даты договора, коды ОКПД2/ИКЗ,
номера приложений. Без этих тестов любая правка регекспов может тихо
вернуть старое поведение.

Запуск: docker compose exec backend python -m pytest -q
"""
import asyncio

import pytest

from app.pii import clean_text


def clean(text: str) -> dict:
    """Синхронная обёртка: тесты гоняем без LLM (llm_classify_dates=None),
    чтобы они были детерминированными и не требовали поднятой Ollama."""
    return asyncio.run(clean_text(text))


# --------------------------------------------------------------------------
# 1. Должно вычищаться
# --------------------------------------------------------------------------

MUST_REMOVE = [
    ("телефон", "Звоните по номеру 89261234567 в рабочее время.", "89261234567"),
    ("email", "Заявки на адрес smirnov85@mail.ru до конца недели.", "smirnov85@mail.ru"),
    ("ИНН", "Поставщик, ИНН 7712345678, подтверждает готовность.", "7712345678"),
    ("СНИЛС", "СНИЛС 112-233-445 95 указан в анкете.", "112-233-445 95"),
    ("паспорт", "Паспорт 45 12 345678 приложен к заявке.", "45 12 345678"),
    ("счёт", "Р/с 40702810123450101230 в банке получателя.", "40702810123450101230"),
    ("карта", "Оплата картой 4276 3800 1234 5678 отклонена.", "4276 3800 1234 5678"),
    ("ФИО", "Директором назначен Смирнов Пётр Николаевич.", "Смирнов"),
    ("организация", "Победителем признано ООО «Ромашка».", "Ромашка"),
    ("филиал", "Отгрузка через филиал в г. Казань.", "филиал в г. Казань"),
]


@pytest.mark.parametrize("label,text,secret", MUST_REMOVE, ids=[c[0] for c in MUST_REMOVE])
def test_pii_is_removed(label, text, secret):
    result = clean(text)
    assert secret not in result["cleaned_text"], (
        f"{label}: значение осталось в тексте -> утечка"
    )
    assert result["entities_found"] > 0
    assert "[" in result["cleaned_text"], "замена должна быть плейсхолдером, а не удалением"


def test_birthdate_removed_but_contract_date_kept():
    """Ключевое требование ТЗ: дата рождения — PII, дата подписания — нет."""
    text = ("Договор подписан 20.08.2026 директором Смирновым Петром Николаевичем, "
            "12.05.1985 года рождения.")
    out = clean(text)["cleaned_text"]
    assert "12.05.1985" not in out, "дата рождения должна вычищаться"
    assert "20.08.2026" in out, "дата подписания договора должна оставаться"


def test_same_value_gets_same_placeholder():
    """Связи между упоминаниями сохраняются: один и тот же телефон -> один плейсхолдер."""
    result = clean("Тел. 89261234567, дублирую: 89261234567.")
    assert result["cleaned_text"].count("[ТЕЛЕФОН_1]") == 2
    assert "[ТЕЛЕФОН_2]" not in result["cleaned_text"]


